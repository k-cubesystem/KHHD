-- 벽 살림(가족 선반장·의식각) 「고정 살림 조절」 오프셋 정리 — 무대 기하 v6
--
-- ── 왜 ───────────────────────────────────────────────────────────────────────
-- CEO 지시(2026-08-12) ①「틀 자리는 맞고, 선반과 간판은 좀 더 뒤로 가야 해」로 벽 살림의 접지선이
-- 82 → 76 으로 물러나고 가족 선반장 규격이 B안(8.65×42 → 6.8×28)으로 바뀌었다.
--
-- 그런데 라이브에 **단 한 채**(소유자 신당)가 「고정 살림 조절」 값을 들고 있고, 그 값은
-- `shrines.updated_at = 2026-07-30` — **무대 기하 v4.1(+11)·v5(+9) 이전**에 저장된 것이다.
-- 즉 사방탁자 밑동이 **62** 이던 시절의 미세 조정이고, 그 뒤로 정본이 두 번(합계 +20%p) 움직였다.
-- 지금 그대로 두면 v6 정본 위에 옛 세대의 보정이 얹혀
--     가족 선반장 76 − 7.54 = **68.46** (마루선 73 보다 위 = 벽 속에 뜬다)
--     의식각      76 + 2.78 = **78.78** (혼자 앞으로 나온다)
-- 가 되어, 이번 회차의 결과를 **볼 수조차 없다**. 검수를 위해 두 키만 정본으로 되돌린다.
--
-- ── 무엇을 남기는가 ─────────────────────────────────────────────────────────
-- `deityStage`(틀) 는 **건드리지 않는다**. CEO 가 "틀 자리는 맞고" 라고 확인한 화면이 그 보정이
-- 얹힌 화면이기 때문이다 — 여기서 지우면 승인된 자리를 우리가 되돌리는 셈이 된다.
--
-- ── 안전 규율 ───────────────────────────────────────────────────────────────
--  · **앵커 정확일치** — 그 세대의 값과 한 글자라도 다르면 건드리지 않는다(20260810c 와 같은 규율).
--    사용자가 v6 배포 후 새로 조절한 값은 이 조건에 걸리지 않는다.
--  · **재실행 무해** — 첫 실행 뒤 키가 사라지므로 두 번째 실행은 0행이다.
--  · **원복 SQL** — 아래 주석의 한 줄이면 그대로 되돌아간다(값을 여기 적어 두는 것이 백업이다):
--      update shrines set fixture_offsets = fixture_offsets
--        || '{"familyShelf":{"dx":-3.83,"dy":-7.54},"ritualHall":{"dx":-3.77,"dy":2.78}}'::jsonb
--       where id = '111af85c-6105-4e70-be93-c543258dd33f';
--  · 배치(shrine_placements)는 **한 건도 건드리지 않는다** — v6 는 동반 이동 SQL 이 0 이다
--    (자유 배치는 사용자가 «거기»에 둔 물건이라는 20260810c 의 규율 그대로).

update shrines
   set fixture_offsets = fixture_offsets - 'familyShelf' - 'ritualHall'
 where fixture_offsets ? 'familyShelf'
   and fixture_offsets -> 'familyShelf' = '{"dx": -3.83, "dy": -7.54}'::jsonb
   and fixture_offsets -> 'ritualHall' = '{"dx": -3.77, "dy": 2.78}'::jsonb;

