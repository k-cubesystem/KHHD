-- 풍수 다중 라벨 사진(슬롯) 대응 프롬프트 지시 (태스크 B)
-- 배경: "한 장으로 집 전체 풍수는 말이 안 된다" — 대상별 라벨 사진 여러 장(사진1=현관, 사진2=거실 …)을
--       한 번에 받아 공간별 개별 진단 → 종합 통합 진단으로 분석한다. 코드(analyzeInteriorForFengshui)가
--       호출 시 "사진N=라벨" 매핑 블록을 동적으로 덧붙이고, 이 마이그레이션은 그 대응을 위한
--       상시 지시 1블록을 멱등 append 한다(태그 스키마는 불변 — 파서 무변경).
-- 방식: 20260723_fengshui_context 와 동일한 NOT LIKE 멱등 UPDATE(후방호환).
-- ⚠️ 프롬프트는 시드로만 관리한다(어드민 UI 폐지) — 여기서만 변경할 것.

UPDATE public.ai_prompts
SET template = template || E'\n\n[다중 사진 대응 지시]\n사용자가 라벨된 사진을 여러 장 제공할 수 있다(예: 사진1=현관, 사진2=거실, 사진3=안방). 이 경우 각 사진(공간)을 먼저 개별 진단하고(공간별 진단은 ROOM_* 태그를 공간마다 적극 사용), 마지막에 공간들의 기운이 상충·보완하는 관계까지 통합한 종합 진단을 제시하라. 사진이 1장뿐이면 기존 방식대로 분석하라. 어떤 경우에도 위 [CRITICAL: 출력 형식]의 태그 스키마는 그대로 유지한다.',
  updated_at = now()
WHERE key = 'fengshui_analysis' AND template NOT LIKE '%다중 사진 대응 지시%';
