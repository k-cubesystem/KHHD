/**
 * 유료 풀이 서술 품질 레이어 — 「같은 모델에서 더 좋은 문장을 뽑는 자리」.
 *
 * ## 왜 이 파일이 생겼나
 * 상위 모델(Claude Fable 5 급)과 Flash 의 문장 격차는 **모델 지능보다 프롬프트에서 더 크게
 * 벌어진다.** 상위 모델은 지시가 엉성해도 스스로 문체를 고르고 상투구를 피하지만, Flash 는
 * 적힌 대로만 쓴다. 그래서 상위 모델에게 «암묵적으로 기대하던 것»을 여기서 **명시적으로 적어
 * 준다.** 모델을 올리는 대신 프롬프트를 올리는 길이고, 원가는 입력 토큰 몇백 개(≈1원/건)다.
 *
 * ## 진단 — 옮기기 전 우리 프롬프트에 있던 세 가지 구멍
 *   ① **말투가 세 곳에서 서로 싸운다.** 마스터 프롬프트는 「무속인 화법(~하시게·~형국이외다)」,
 *      테마 규율은 「~합니다 체 · 무속 표현 금지」, 종합사주 지침은 「요체(~요) 필수」다.
 *      상위 모델은 맥락으로 하나를 고르지만 Flash 는 **문단마다 흔들린다.**
 *   ② **금지만 있고 실연이 없다.** 「이렇게 쓰지 마라」는 많은데 「이렇게 써라」의 문장 예시가
 *      하나도 없었다. 좋은 산문을 만드는 가장 강한 레버가 대비 예시인데 그게 비어 있었다.
 *   ③ **문장을 짓는 규율이 없다.** 길이 리듬·구체 명사·비유 밀도 같은 공예 지시가 없으면
 *      Flash 는 안전한 문장, 즉 **누구에게나 해당되는 문장**으로 수렴한다. 그게 「AI 티」의 정체다.
 *
 * ## 두 겹으로 나뉜다
 *   · **용어 예산**(`TERM_DISCIPLINE`) — 유료·무료 **모두**. 읽기 쉬움은 등급이 아니라 기본이고,
 *     무료가 어려우면 유료로 넘어올 이유도 생기지 않는다.
 *   · **문장 공예**(`PREMIUM_PROSE_LAYER`) — 유료 장문만. 무료 경로(고민상담·오늘의 운세·신탁)는
 *     출력이 44~245 토큰이라 공예가 드러나지 않고, 매출이 0인데 사용량만 는다(보고서 §5).
 *
 * 근거 문서: `docs/REPORTS/RESEARCH-20260814-llm-model-selection.md` §7
 */

/** 서술 등급 — 유료 장문만 `premium`. */
