/**
 * 「1:1 문의」 — 사용자를 문의 게시판으로 보내는 **말과 주소의 단일 출처**.
 *
 * 🔴 왜 상수로 묶는가 (2026-08-26).
 *    같은 창구를 화면마다 다른 이름으로 부르고 있었다. 푸터는 「고객센터」, 결제 오류는
 *    「고객센터로 문의해주세요」, 취소 화면은 「고객센터로 문의하기」 — 정작 그 모두가 가리키는
 *    곳은 하나(`/protected/support`, 1:1 문의 게시판)였다. 이름이 물건을 감춰서 CEO 조차
 *    «1:1 문의 게시판을 넣어 달라»고 했다(이미 있었는데도).
 *    사용자가 «어디로 가야 하는지»를 한 번만 배우게 하려면 이름이 하나여야 한다.
 *
 * 🔴 화면에 「고객센터」를 다시 쓰지 말 것. 이 앱에는 전화 상담·FAQ 같은 «센터»가 없다 —
 *    없는 물건을 가리키는 이름이다. 회귀는 `__tests__/contact.test.ts` 가 소스를 훑어 막는다.
 *    (전화번호·운영시간은 푸터 사업자 정보에 따로 있고, 그건 «센터»가 아니라 연락처다.)
 *
 * 순수 상수 모듈 — 서버 액션·클라이언트 컴포넌트 양쪽에서 쓴다.
 */

/** 창구의 이름. 화면에 쓰는 유일한 호칭이다. */
export const SUPPORT_LABEL = '1:1 문의'

/** 창구의 주소. 링크를 새로 적지 말고 이 값을 쓴다. */
export const SUPPORT_HREF = '/protected/support'

/**
 * 「여기로 알려 주세요」 한 문장.
 *
 * 「1:1 문의로 문의해주세요」는 겹말이라 쓰지 않는다 — 게시판에 글을 **남기는** 행위라
 * 「남겨 주세요」가 실제 동작과 맞는다.
 */
export const SUPPORT_ASK = `${SUPPORT_LABEL}를 남겨주세요.`

/** 되풀이되는 문제에 붙이는 안내. 원인을 우리가 먼저 확인하겠다는 약속까지 담는다. */
export const SUPPORT_ASK_REPEAT = `같은 일이 반복되면 ${SUPPORT_LABEL}로 알려주세요.`

/** 버튼·링크에 붙는 짧은 행동 문구. */
export const SUPPORT_CTA = `${SUPPORT_LABEL}하기`

/** 오류 문장 뒤에 붙이는 꼬리 — `${사유} ${supportSuffix()}` 로 쓴다. */
export function supportSuffix(): string {
  return SUPPORT_ASK
}
