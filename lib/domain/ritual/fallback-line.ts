/** 폴백 기본값 — 일간을 모르는 극단 케이스(명식 파싱 실패)용 */
const GENERIC_LINE = '이번 달도 무탈하게 — 초하루에 식구들 안부를 여쭙는 것으로 복을 엽니다.'

/**
 * (일간 한자, 음력 월 서수) → 결정론 1줄.
 * dayGanHan: calculateManse(...).day.gan (한자 천간)
 */
export function ritualFallbackLine(dayGanHan: string | null | undefined, seq: number): string {
  if (!dayGanHan) return GENERIC_LINE
  const slug = ilganSlugFromHan(dayGanHan)
  if (!slug) return GENERIC_LINE
  const variants = MONTHLY_LINES[slug]
  const line = variants[((seq % variants.length) + variants.length) % variants.length]
  return `${ILGAN[slug].name}의 달 문안 — ${line}`
}
