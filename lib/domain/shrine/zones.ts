export function clampPct(v: number, range: [number, number]): number {
  return Math.min(range[1], Math.max(range[0], v))
}

/**
 * 새 아이템이 떨어지는 기준선 y — **존 중점에서 파생하지 않는다**(전부 v1 중점값 동결).
 * v2 에서 존이 크게 넓어졌으므로 중점 파생을 두면 보관함에서 꺼낸 아이템의 첫 자리가
 * 이유 없이 이동한다(hanging 14→23 등). 자유는 드래그의 몫이고 기본값은 어제와 같아야 한다.
 */
const HOME_Y: Record<Layer, number> = {
  hanging: 14,
  wall: 32.5,
  altar: 52,
  floor: 77,
}

/** 새 아이템을 존 기준선 부근에 놓을 초기 좌표 (겹침 완화용 랜덤 지터) */
export function initialSpot(layer: Layer, jitter: number): { x: number; y: number } {
  const z = ZONES[layer]
  const midX = (z.x[0] + z.x[1]) / 2
  const spanX = (z.x[1] - z.x[0]) / 2 - 6
  return {
    x: clampPct(midX + (jitter - 0.5) * spanX, z.x),
    y: HOME_Y[layer],
  }
}

